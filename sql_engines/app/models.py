"""ORM models for a tiny shop: products and the orders placed against them.

The same models run on PostgreSQL, MySQL, SQL Server and SQLite. Constraint names are
fixed by a naming convention so that every engine reports the same names, and so that
the migrations and the models can be compared without noise.
"""

from typing import cast

from sqlalchemy import CheckConstraint, ForeignKey, Identity, MetaData, String, Table, Unicode
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "ix": "ix_%(table_name)s_%(column_0_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class Product(Base):
    __tablename__ = "products"

    # Identity() renders as GENERATED BY DEFAULT AS IDENTITY on PostgreSQL, IDENTITY on
    # SQL Server, AUTO_INCREMENT on MySQL and a rowid alias on SQLite.
    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    sku: Mapped[str] = mapped_column(String(32), unique=True)
    # Unicode -> NVARCHAR on SQL Server, where plain VARCHAR can't hold all characters.
    name: Mapped[str] = mapped_column(Unicode(100))
    price_cents: Mapped[int]
    stock: Mapped[int]
    # Optimistic locking: every UPDATE includes "WHERE version = <the version I read>"
    # and bumps it, so a write based on stale data matches zero rows and fails.
    version: Mapped[int] = mapped_column(server_default="1")

    __table_args__ = (
        CheckConstraint("price_cents > 0", name="price_positive"),
        CheckConstraint("stock >= 0", name="stock_not_negative"),
    )
    __mapper_args__ = {"version_id_col": version}


class Order(Base):
    __tablename__ = "orders"

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id"))
    quantity: Mapped[int]
    customer_email: Mapped[str] = mapped_column(String(255))

    __table_args__ = (CheckConstraint("quantity > 0", name="quantity_positive"),)


# Core handles on the same tables, for statements that skip the ORM. (The cast is only
# for the type checker: __table__ is typed loosely, but here it is always a Table.)
products_table = cast(Table, Product.__table__)
orders_table = cast(Table, Order.__table__)
